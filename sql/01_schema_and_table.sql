-- Creating schema
CREATE SCHEMA IF NOT EXISTS ANALYTICS;

-- Creating table
DROP TABLE IF EXISTS ANALYTICS.STUDENTS;

CREATE TABLE ANALYTICS.STUDENTS (
    STUDENT_ID VARCHAR(20) PRIMARY KEY,
    AGE INT,
    GENDER VARCHAR(20),
    CITY VARCHAR(50),
    DEPARTMENT VARCHAR(100),
    COURSE VARCHAR(100),
    STUDY_HOURS_PER_DAY NUMERIC(4, 1),
    ATTENDANCE_PERCENTAGE NUMERIC(5, 1),
    ASSIGNMENT_SCORE INT,
    MIDTERM_SCORE INT,
    FINAL_SCORE INT,
    TOTAL_SCORE NUMERIC(5, 1),
    GRADE VARCHAR(5),
    EXAM_STATUS VARCHAR(10),
    SCHOLARSHIP VARCHAR(5),
    INTERNET_ACCESS VARCHAR(5),
    EXTRACURRICULAR VARCHAR(5),
    PARENT_EDUCATION VARCHAR(30)
);
